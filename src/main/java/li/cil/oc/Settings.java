    public static Settings get() {
        Settings current = instance;
        if (current != null) return current;
        synchronized (Settings.class) {
            if (instance == null) instance = new Settings(defaults().getConfig("opencomputers"));
            return instance;
        }
    }
    private static Config defaults() {
        try (InputStream stream = Settings.class.getResourceAsStream("/application.conf")) {
            if (stream == null) throw new IllegalStateException("Missing OpenComputers application.conf");
            return ConfigFactory.parseString(new String(stream.readAllBytes(), StandardCharsets.UTF_8)
                .replace("@VERSION@", "0.1.0-SNAPSHOT")).resolve();
        } catch (IOException exception) { throw new UncheckedIOException(exception); }
    }
    public static synchronized void load(Path path) throws IOException {
        Config base = defaults();
        Config effective = Files.exists(path) ? ConfigFactory.parseFile(path.toFile()).withFallback(base).resolve() : base;
        instance = new Settings(effective.getConfig("opencomputers"));
        Files.createDirectories(path.toAbsolutePath().getParent());
        Files.writeString(path, effective.root().render(ConfigRenderOptions.defaults().setJson(false).setOriginComments(false)), StandardCharsets.UTF_8);
    }
