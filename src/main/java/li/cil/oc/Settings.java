    public enum DebugCardAccess {
        Allowed, Forbidden, Whitelist;
        public Optional<String> checkAccess(Optional<li.cil.oc.common.item.data.DebugCardData.AccessContext> access) {
            if (this == Allowed) return Optional.empty();
            if (this == Forbidden) return Optional.of("debug card is disabled");
            if (access.isEmpty()) return Optional.of("debug card is whitelisted, Shift+Click with it to bind card to yourself");
            var context = access.get();
            Optional<String> nonce = li.cil.oc.server.component.DebugAccess.nonce(context.player());
            if (nonce.isEmpty()) return Optional.of("you are not whitelisted to use debug card");
            return nonce.get().equals(context.nonce()) ? Optional.empty() : Optional.of("debug card is invalidated, please re-bind it to yourself");
        }
    }
    public static Settings get() {
        Settings current = instance;
        if (current != null) return current;
        synchronized (Settings.class) {
            if (instance == null) instance = new Settings(defaults().getConfig("opencomputers"));
            return instance;
        }
    }
    private static Config defaults() {
        try (InputStream stream = Settings.class.getResourceAsStream("/application.conf")) {
            if (stream == null) throw new IllegalStateException("Missing OpenComputers application.conf");
            return ConfigFactory.parseString(new String(stream.readAllBytes(), StandardCharsets.UTF_8)
                .replace("@VERSION@", OpenComputers.VERSION)).resolve();
        } catch (IOException exception) { throw new UncheckedIOException(exception); }
    }
    public static synchronized void load(Path path) throws IOException {
        Config base = defaults();
        final SettingsMigration.Result migration;
        final Config effective;
        final Settings loaded;
        try {
            Config raw = Files.exists(path)
                    ? ConfigFactory.parseFile(path.toFile(), ConfigParseOptions.defaults().setAllowMissing(false))
                    : ConfigFactory.empty();
            // Resolve user substitutions without adding fallback keys before version detection.
            raw = raw.resolveWith(raw.withFallback(base));
            migration = SettingsMigration.patch(raw, base, OpenComputers.VERSION);
            effective = migration.config().withFallback(base).resolve();
            loaded = new Settings(effective.getConfig("opencomputers"));
        } catch (RuntimeException error) {
            throw new IOException("Error parsing OpenComputers configuration '" + path.toAbsolutePath()
                    + "'. The existing file was left unchanged. Fix the reported option, or move the file aside and restart to regenerate defaults. "
                    + error.getMessage(), error);
        }
        // Publish only after all fields have been read and validated successfully.
        instance = loaded;
        String rendered = render(effective);
        Path absolute = path.toAbsolutePath();
        Path temporary = null;
        try {
            if (Files.exists(absolute) && Files.readString(absolute, StandardCharsets.UTF_8).equals(rendered)) return;
            Files.createDirectories(absolute.getParent());
            if (migration.changed() && Files.exists(absolute)) {
                String stamp = java.time.format.DateTimeFormatter.ofPattern("yyyyMMdd-HHmmss-SSS")
                        .withZone(java.time.ZoneOffset.UTC).format(java.time.Instant.now());
                Path backup = absolute.resolveSibling(absolute.getFileName() + ".migration-" + stamp + ".bak");
                Files.copy(absolute, backup, StandardCopyOption.COPY_ATTRIBUTES);
                OpenComputers.LOGGER.info("Backed up configuration before migration to {}", backup);
            }
            for (String change : migration.changes()) OpenComputers.LOGGER.info("Configuration migration: {}", change);
            temporary = Files.createTempFile(absolute.getParent(), absolute.getFileName() + ".", ".tmp");
            Files.writeString(temporary, rendered, StandardCharsets.UTF_8);
            try { Files.move(temporary, absolute, StandardCopyOption.ATOMIC_MOVE, StandardCopyOption.REPLACE_EXISTING); }
            catch (AtomicMoveNotSupportedException unsupported) { Files.move(temporary, absolute, StandardCopyOption.REPLACE_EXISTING); }
        } catch (IOException error) {
            // Upstream allows a valid, read-only configuration to run even if regeneration fails.
            OpenComputers.LOGGER.warn("Failed saving OpenComputers configuration {}; the existing file was retained.", absolute, error);
        } finally {
            if (temporary != null) try { Files.deleteIfExists(temporary); } catch (IOException ignored) {}
        }
    }
    private static String render(Config config) {
        String newline = System.lineSeparator();
        StringBuilder result = new StringBuilder();
        String rendered = config.root().render(ConfigRenderOptions.defaults().setJson(false).setOriginComments(false));
        for (String line : rendered.split("\\R")) {
            int spaces = 0; while (spaces < line.length() && line.charAt(spaces) == ' ') spaces++;
            result.append(" ".repeat(spaces / 2)).append(line.substring(spaces)).append(newline);
        }
        return result.toString();
    }
